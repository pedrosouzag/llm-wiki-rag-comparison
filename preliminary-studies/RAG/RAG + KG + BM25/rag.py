"""Montar chunks para ler  wiki"""

def montar_chunks(PASTA_WIKI):
    chunks = []
    with open(PASTA_WIKI, "r", encoding="utf-8") as arquivo:
        texto = arquivo.read()
        for linha in texto.splitlines()[:100]:
           temp = json.loads(linha)
           for paragrafo in temp["paragraphs"]:
              titulo = paragrafo["title"]
              conteudo = paragrafo["paragraph_text"]
              chunks.append({"fonte": titulo, "texto" : titulo + "\n" + conteudo})

    return chunks

"""## Gerando os Embeddings e comparando os mais próximos no espaco (Vetorial)"""

def get_embedding(chunks):
    embeddings = []
    for chunk in chunks:
        temp = "passage: " + chunk["texto"]
        embeddings.append(model_embedding.encode(temp, normalize_embeddings=True))
    return np.array(embeddings)

def pegar_nota(par):
    return par[1]

def search_chunks(pergunta, chunks, vetorEmbedding, k = 5):
  perguntaAtt = model_embedding.encode("query: " + pergunta, normalize_embeddings=True)
  notas = vetorEmbedding @ perguntaAtt

  # enumera as notas, depois ordena para as maiores, deixe em ordem decrescente e pega as 5 maiores
  maiores = sorted(enumerate(notas), key=pegar_nota, reverse=True)[:k]

  resultado = []

  for i, nota in maiores:   # i = posicao, nota = nota, chunks[i] é o chunk daquela posicao
      resultado.append((chunks[i], float(nota)))
  return resultado

