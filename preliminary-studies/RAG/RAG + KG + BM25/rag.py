def gerar_gemma_12b(prompt, max_tokens=350):

    mensagens = [{"role": "user", "content": prompt}]
    inputs = tokenizer2.apply_chat_template(mensagens, add_generation_prompt=True, return_tensors="pt", return_dict=True).to(model2.device)  # formata como conversa, assim o modelo sabe onde parar

    outputs = model2.generate(**inputs, max_new_tokens=max_tokens, do_sample=False, pad_token_id=tokenizer2.eos_token_id)

    tamanho_entrada = inputs["input_ids"].shape[1]
    resposta_ids = outputs[0][tamanho_entrada:]  # pega só os tokens novos, sem repetir o prompt

    resposta = tokenizer2.decode(resposta_ids, skip_special_tokens=True).strip()

    return resposta



