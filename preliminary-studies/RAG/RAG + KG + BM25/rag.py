def get_Perguntas(PASTA_WIKI):
  perguntas = []
  respostas = []

  with open(PASTA_WIKI, "r", encoding="utf-8") as arquivo:
     texto = arquivo.read()
     for linha in texto.splitlines()[:100]:
        temp = json.loads(linha) # transformar a linha em dicionario python

        # pega a questao e a resposta
        # answer_aliases = variacoes de palavras nas respostas
        questao = temp["question"]
        resposta = [temp["answer"]] + temp["answer_aliases"]

        # adiciona nas listas
        perguntas.append(questao)
        respostas.append(resposta)

  return perguntas, respostas


