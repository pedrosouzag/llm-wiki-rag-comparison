def extrair_Triplas(texto):
  # prompt pedindo pro gemma tirar as triplas do texto, com um exemplo do formato
  prompt = f""" Extract the facts from the text as triples, one per line, in the format:
    source | relation | target

    Use full names (never "he", "it" or "the album") and only what is in the text.
    Keep the same language as the text. Do not translate.
    Write only the triples. If there are no facts, write: none

    Example:
    Text: Abbey Road is the eleventh studio album by the Beatles, released in 1969 by Apple Records. It was recorded at EMI Studios in London.
    Abbey Road | is an album by | the Beatles
    Abbey Road | released in | 1969
    Abbey Road | released by | Apple Records
    Abbey Road | recorded at | EMI Studios
    EMI Studios | located in | London

    Text: {texto}"""

  temp = gerar_gemma_12b(prompt, max_tokens=300)

  if temp.strip().lower() == "none":
    return []
  else:
    triplas = []
    # analisa as linhas
    for linha in temp.split("\n"):
      partes = linha.split("|")
      # pula linha vazia ou fora do formato que precisa ter exatamente 3 partes
      if len(partes) != 3:
        continue
      origem, relacao, destino = partes
      triplas.append((origem.strip(), relacao.strip(), destino.strip()))
    return triplas

def build_KG(chunks):
  KG = nx.MultiDiGraph()

  # tira as triplas dos chunks, ex chunk 1 tira origem, detino e relacao - pode ter mais de uma tripla por chunk
  i = 0
  for chunk in chunks:
    triplas = extrair_Triplas(chunk["texto"])

    for origem, relacao, destino in triplas:
      KG.add_edge(origem, destino, relacao = relacao, chunk = i)   # guarda de qual chunk veio

    i += 1
  return KG

def search_chunks_KG(pergunta, chunks, KG):
  palavras_pergunta = set(tokenizar(pergunta))

  # lista onde vao os nos do grafo que aparecem na pergunta
  nos_similares = []

  for no in KG:
    palavras_no = set(tokenizar(no))
    if len(palavras_no) == 0:
      continue
    similares = palavras_no & palavras_pergunta
    similaridade = len(similares) / len(palavras_no)
    if similaridade > 0.5:
      nos_similares.append(no)

  arestas = []
  for no in nos_similares:
    # pega todas as arestas dos nos similares
    arestas_entrada = KG.in_edges(no, data = True)
    arestas_saida = KG.out_edges(no, data = True)

    # extend coloca cada aresta na lista como um item separado
    # in_edges e out_edges devolvem uma "view" da networkx: funciona como uma lista
    arestas.extend(arestas_entrada)
    arestas.extend(arestas_saida)

  num_chunk = []
  for origem, destino, atributos in arestas:
    num_chunk.append(atributos["chunk"])


  # conta quantas vezes cada chunk apareceu e pega os 5 que mais apareceram
  mais_repetidos = Counter(num_chunk).most_common(5)

  # troca o numero do chunk pelo chunk de verdade e usa as vezes como nota
  resultado = []
  for numero, vezes in mais_repetidos:
    resultado.append((chunks[numero], vezes))

  return resultado

def print_KG(achados):
  for chunk, vezes in achados:
    primeira_linha = chunk["texto"].split("\n")[0]  # pega so a primeira linha do chunk
    print(vezes, primeira_linha)                     # quantas arestas levaram ao chunk e a primeira linha



"""## Função de Pergunta"""

def montar_contexto(pergunta, flag):
  # se for vetor
  if flag == 1:
    achados = search_chunks(pergunta, chunks, vetores, k = 5)
  # se for bm25
  elif flag == 2:
    achados = search_chunks_BM25(pergunta, chunks, bm25)
  # se for KG
  elif flag == 3:
    achados = search_chunks_KG(pergunta, chunks, KG)

  # se for vetor, kg e bm25 juntos
  elif flag == 4:
    # pega os chunks das 3 funcoes de busca
    chunks_Vetor = search_chunks(pergunta, chunks, vetores, k = 5)
    chunks_BM25 = search_chunks_BM25(pergunta, chunks, bm25)
    chunks_KG = search_chunks_KG(pergunta, chunks, KG)

    # junta as 3 listas, mas tirando os chunks que se repetem
    achados = []
    for chunk, nota in chunks_Vetor + chunks_BM25 + chunks_KG:
      repetido = False
      for chunk_existente, nota_existente in achados:
        if chunk["texto"] == chunk_existente["texto"]:
          repetido = True
          break
      if not repetido:
        achados.append((chunk, nota))
  # retorna o contexto
  contexto = ""
  for chunk, nota in achados:
    contexto += chunk["texto"] + "\n\n"

  return contexto, achados

def perguntar_rag(pergunta, contexto):
    max_tokens = 40

    prompt = f"""You are an assistant that answers questions.
        Use only the passages below. Answer in English with only the answer itself:
        a name, a place, a date or a number. No full sentence, no explanation.
        If the answer is not in the passages, write: not found. Do not make anything up.

        Passages:
        {contexto}

        Question: {pergunta}
        Answer:"""

    return gerar_gemma_12b(prompt, max_tokens=max_tokens)


def verificar_Resposta(resposta, resposta_certa):
    # cria uma lista para tirar os artigos da resposta
    resposta_sem_artigo = []

    # tokeniza a resposta na funca reaproveitada do KG
    resposta_tokenizada = tokenizar(resposta)
    # remove os artigos
    for  palavra in resposta_tokenizada:
      if palavra not in ["a", "the" , "an"]:
        resposta_sem_artigo.append(palavra)
    # em cada variacao de respota certa, tokeniza, tira o artigo e compara com a resposta que o modelo deu, se for igual certo, se nao, falso
    for certa in resposta_certa:
       certa_sem_artigo = []
       certa_tokenizada = tokenizar(certa)
       for palavra in certa_tokenizada:
             if palavra not in ["a", "the" , "an"]:
               certa_sem_artigo.append(palavra)
       if resposta_sem_artigo == certa_sem_artigo:
          return True
    return False
       

    

